package com.tuatua.entity;

/**
 * Định nghĩa các vai trò trong hệ thống.
 * MEMBER: Dành cho người dùng thông thường (Học sinh, Phụ huynh).
 * STAFF: Dành cho nhân viên (ví dụ: ban tư vấn, giáo vụ).
 * ADMIN: Dành cho quản trị viên hệ thống.
 */
public enum Role {
    MEMBER,
    STAFF,
    ADMIN
}